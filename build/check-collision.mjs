import assert from 'node:assert/strict';
import { collisionFor, isShipwreck, transitionDuration } from '../public/collision.js';
const round = statuses => ({id:'same-voyage',containers:statuses.map((status,i)=>({id:['A','B','C'][i],status}))});
const aboard=round(['onboard','onboard','onboard']);
const one=round(['lost','onboard','onboard']),two=round(['lost','lost','onboard']),all=round(['lost','lost','lost']);
assert.deepEqual(collisionFor(aboard,one),{kind:'debris',lost:['A']});
assert.deepEqual(collisionFor(aboard,two),{kind:'debris',lost:['A','B']});
assert.deepEqual(collisionFor(aboard,all),{kind:'iceberg',lost:['A','B','C']});
assert.deepEqual(collisionFor(two,all),{kind:'iceberg',lost:['C']});
assert.deepEqual(collisionFor(round(['collected','lost','onboard']),round(['collected','lost','lost'])),{kind:'debris',lost:['C']});
assert.equal(isShipwreck(round(['collected','lost','lost'])),false);
assert.equal(isShipwreck(all),true);
assert.equal(isShipwreck(null),false);
assert.equal(collisionFor(one,one),null);
assert.equal(collisionFor(aboard,round(['collected','onboard','onboard']),'collect'),null);
assert.equal(collisionFor(aboard,{...all,id:'different-voyage'}),null);
assert.equal(collisionFor(null,all),null);
assert.equal(transitionDuration('sail',collisionFor(aboard,all),true),90);
assert.ok(transitionDuration('sail',collisionFor(aboard,all))>transitionDuration('sail',collisionFor(aboard,one)));
